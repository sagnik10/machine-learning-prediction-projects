import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
from sklearn.model_selection import train_test_split
from sklearn.linear_model import LinearRegression, Ridge
from sklearn.svm import SVR
from sklearn.ensemble import RandomForestRegressor
from sklearn.preprocessing import StandardScaler
from sklearn.metrics import mean_absolute_error, mean_squared_error, r2_score
from fpdf import FPDF
import os

base_dir=os.path.dirname(os.path.abspath(__file__))
output_dir=os.path.join(base_dir,"output")
charts_dir=os.path.join(output_dir,"charts")

os.makedirs(charts_dir,exist_ok=True)

np.random.seed(42)

days=300

data=pd.DataFrame({
'Open':np.random.uniform(100,200,days),
'High':np.random.uniform(110,210,days),
'Low':np.random.uniform(90,190,days),
'Close':np.random.uniform(100,200,days),
'Volume':np.random.randint(1000000,5000000,days)
})

data['Next_Close']=data['Close'].shift(-1)
data=data.dropna()

features=['Open','High','Low','Close','Volume']
target='Next_Close'

X=data[features]
y=data[target]

scaler=StandardScaler()
X_scaled=scaler.fit_transform(X)

X_train,X_test,y_train,y_test=train_test_split(X_scaled,y,test_size=0.2,random_state=42)

models={
"Linear Regression":LinearRegression(),
"Ridge Regression":Ridge(alpha=1.0),
"SVR":SVR(kernel='rbf'),
"Random Forest":RandomForestRegressor(n_estimators=200,random_state=42)
}

metrics=[]
results={}

for name,model in models.items():

    model.fit(X_train,y_train)

    pred=model.predict(X_test)

    rmse=np.sqrt(mean_squared_error(y_test,pred))
    mae=mean_absolute_error(y_test,pred)
    r2=r2_score(y_test,pred)

    metrics.append([name,rmse,mae,r2])

    result=pd.DataFrame({
        'Actual':y_test.values,
        'Predicted':pred
    })

    results[name]=result

    plt.figure(figsize=(8,4))
    plt.plot(result['Actual'].values,label='Actual',marker='o')
    plt.plot(result['Predicted'].values,label='Predicted',marker='x')
    plt.title(name+" Prediction")
    plt.xlabel("Samples")
    plt.ylabel("Stock Price")
    plt.legend()
    plt.tight_layout()

    chart_path=os.path.join(charts_dir,name.replace(" ","_")+"_prediction.png")
    plt.savefig(chart_path)
    plt.close()

rf=models["Random Forest"]
importances=rf.feature_importances_

plt.figure(figsize=(6,4))
plt.bar(features,importances)
plt.title("Feature Importance - Random Forest")
plt.xlabel("Features")
plt.ylabel("Importance")
plt.tight_layout()

fi_path=os.path.join(charts_dir,"feature_importance.png")
plt.savefig(fi_path)
plt.close()

metrics_df=pd.DataFrame(metrics,columns=['Model','RMSE','MAE','R2'])

prediction_table=pd.DataFrame()

for model in results:
    temp=results[model].copy()
    temp.columns=[model+"_Actual",model+"_Predicted"]
    prediction_table=pd.concat([prediction_table,temp],axis=1)

csv_path=os.path.join(output_dir,"stock_predictions.csv")
prediction_table.to_csv(csv_path,index=False)

metrics_path=os.path.join(output_dir,"model_metrics.csv")
metrics_df.to_csv(metrics_path,index=False)

