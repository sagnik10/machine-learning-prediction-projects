pdf.set_auto_page_break(auto=True,margin=15)
pdf.add_page()

pdf.set_font("Arial","B",18)
pdf.cell(0,10,"Stock Price Prediction Report",0,1,'C')

pdf.set_font("Arial","",12)

text="""This report presents a machine learning based stock price forecasting system using regression models. Multiple algorithms including Linear Regression, Ridge Regression, Support Vector Regression, and Random Forest are applied to predict the next closing price of a stock using OHLCV features (Open, High, Low, Close, Volume). The charts below compare predicted values with actual values to evaluate model performance."""

pdf.multi_cell(0,8,text)

pdf.ln(5)

pdf.set_font("Arial","B",14)
pdf.cell(0,10,"Evaluation Metrics",0,1)

pdf.set_font("Arial","",11)

for i,row in metrics_df.iterrows():

    line=f"{row['Model']} | RMSE: {row['RMSE']:.2f} | MAE: {row['MAE']:.2f} | R2 Score: {row['R2']:.2f}"

    pdf.cell(0,8,line,0,1)

pdf.add_page()

for model in models:

    pdf.set_font("Arial","B",14)
    pdf.cell(0,10,model+" Prediction Chart",0,1)

    img=os.path.join(charts_dir,model.replace(" ","_")+"_prediction.png")
    pdf.image(img,w=170)

    pdf.ln(5)

    explanation=f"This chart compares actual and predicted stock closing prices generated by the {model} regression model. The model analyzes historical price features and trading volume to estimate the next closing price."

    pdf.set_font("Arial","",11)
    pdf.multi_cell(0,8,explanation)

    pdf.ln(5)

pdf.add_page()

pdf.set_font("Arial","B",14)
pdf.cell(0,10,"Feature Importance (Random Forest)",0,1)

pdf.image(fi_path,w=150)

pdf.ln(5)

pdf.set_font("Arial","",11)

exp2="""The feature importance chart shows how different input variables contribute to stock price prediction. Random Forest assigns higher importance to features that significantly influence price movement such as closing price and trading volume."""

pdf.multi_cell(0,8,exp2)

pdf.add_page()

pdf.set_font("Arial","B",14)
pdf.cell(0,10,"Prediction Table Sample",0,1)

sample=prediction_table.head(10)

pdf.set_font("Arial","",9)

for col in sample.columns:
    pdf.cell(35,8,col,1)

